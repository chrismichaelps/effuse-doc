import { discoverServerRegistry, writeServerRegistryModule } from '@effuse/cli';
import { readFileSync, writeFileSync } from 'node:fs';

const registry = discoverServerRegistry(process.cwd());
const outputPath = writeServerRegistryModule(registry);
const generatedSource = readFileSync(outputPath, 'utf8');

// @effuse/cli 1.0.3 narrows an all-API registry too aggressively inside its
// compatibility loader. Runtime generation is correct; suppress that emitted
// implementation-only diagnostic until effuse#473 is released.
writeFileSync(
  outputPath,
  generatedSource.replace(
    '// Generated by @effuse/cli. Do not edit.',
    '// Generated by @effuse/cli. Do not edit.\n// @ts-nocheck'
  )
);

console.log(
  `[effuse] generated ${registry.entries.length} server endpoints at ${outputPath}`
);
